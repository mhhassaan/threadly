import { betterAuth } from 'better-auth/minimal'
import { drizzleAdapter } from 'better-auth/adapters/drizzle'
import type { Platform } from '../platform'
import { createDb } from '../data/db'
import { isLoopback, sendAccountEmail } from './email'
import * as schema from './schema'

let localSecret: string | undefined
export function createAuth(platform: Platform) {
  const { env } = platform
  const local = env.dev && isLoopback(env.authUrl)
  let secret = env.authSecret
  if (!secret && local)
    secret = localSecret ??= crypto.randomUUID() + crypto.randomUUID()
  if (secret.length < 32)
    throw new Error('Authentication secret is not configured')
  if (
    !local &&
    (new URL(env.authUrl).protocol !== 'https:' ||
      env.emailTransport !== 'resend' ||
      !env.resendApiKey ||
      !env.resendFrom)
  )
    throw new Error('Production authentication is not configured')
  const sendLink = async (to: string, url: string, action: string) => {
    // The link is generated by Better Auth. Escape it before interpolating into HTML.
    const escaped = url
      .replaceAll('&', '&amp;')
      .replaceAll('"', '&quot;')
      .replaceAll('<', '&lt;')
      .replaceAll('>', '&gt;')
    const digest = await crypto.subtle.digest(
      'SHA-256',
      new TextEncoder().encode(url),
    )
    const idempotencyKey = Array.from(new Uint8Array(digest), (x) =>
      x.toString(16).padStart(2, '0'),
    ).join('')
    await sendAccountEmail(platform, {
      to,
      subject: `${action} — Threadly`,
      text: `${action}: ${url}`,
      html: `<p><a href="${escaped}">${action}</a></p>`,
      idempotencyKey,
    })
  }
  return betterAuth({
    appName: 'Threadly',
    baseURL: env.authUrl,
    basePath: '/api/auth',
    secret,
    database: drizzleAdapter(createDb(platform.db), {
      provider: 'sqlite',
      schema,
      transaction: false,
    }),
    trustedOrigins: [new URL(env.authUrl).origin],
    emailAndPassword: {
      enabled: true,
      requireEmailVerification: true,
      minPasswordLength: 12,
      maxPasswordLength: 128,
      resetPasswordTokenExpiresIn: 3600,
      revokeSessionsOnPasswordReset: true,
      sendResetPassword: async ({ user, url }) =>
        sendLink(user.email, url, 'Reset your password'),
    },
    emailVerification: {
      sendOnSignUp: true,
      sendOnSignIn: true,
      autoSignInAfterVerification: false,
      expiresIn: 3600,
      sendVerificationEmail: async ({ user, url }) =>
        sendLink(user.email, url, 'Verify your email'),
    },
    session: {
      expiresIn: 60 * 60 * 24 * 7,
      updateAge: 60 * 60 * 24,
      cookieCache: { enabled: false },
    },
    rateLimit: {
      enabled: true,
      storage: 'database',
      modelName: 'rate_limit',
      window: 60,
      max: 100,
      customRules: {
        '/sign-in/email': { window: 60, max: 10 },
        '/sign-up/email': { window: 60, max: 5 },
        '/request-password-reset': { window: 60, max: 5 },
        '/send-verification-email': { window: 60, max: 5 },
      },
    },
    advanced: {
      useSecureCookies: !local,
      defaultCookieAttributes: { httpOnly: true, sameSite: 'lax', path: '/' },
      disableOriginCheck: false,
      ipAddress: { ipAddressHeaders: ['cf-connecting-ip'] },
      backgroundTasks: { handler: (work) => platform.waitUntil(work) },
    },
    // Auth errors must never dump request bodies, tokens or delivery links.
    logger: { disabled: true },
    telemetry: { enabled: false },
  })
}
