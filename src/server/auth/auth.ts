import { betterAuth } from 'better-auth/minimal'
import { APIError, createAuthMiddleware } from 'better-auth/api'
import { drizzleAdapter } from 'better-auth/adapters/drizzle'
import { ApiError } from '../../lib/account-thread'
import type { Platform } from '../platform'
import { createDb } from '../data/db'
import { isLoopback, sendAccountEmail } from './email'
import * as schema from './schema'

let localSecret: string | undefined
export function createAuth(platform: Platform) {
  const { env } = platform
  const local = env.dev && isLoopback(env.authUrl)
  let secret = env.authSecret
  if (!secret && local)
    secret = localSecret ??= crypto.randomUUID() + crypto.randomUUID()
  if (secret.length < 32)
    throw new ApiError(
      503,
      'AUTH_UNAVAILABLE',
      'Authentication is not configured',
    )
  if (
    !local &&
    (new URL(env.authUrl).protocol !== 'https:' ||
      env.emailTransport !== 'resend' ||
      !env.resendApiKey ||
      !env.resendFrom)
  )
    throw new ApiError(
      503,
      'AUTH_UNAVAILABLE',
      'Authentication is not configured',
    )
  const sendLink = async (to: string, url: string, action: string) => {
    // The link is generated by Better Auth. Escape it before interpolating into HTML.
    const escaped = url
      .replaceAll('&', '&amp;')
      .replaceAll('"', '&quot;')
      .replaceAll('<', '&lt;')
      .replaceAll('>', '&gt;')
    const digest = await crypto.subtle.digest(
      'SHA-256',
      new TextEncoder().encode(url),
    )
    const idempotencyKey = Array.from(new Uint8Array(digest), (x) =>
      x.toString(16).padStart(2, '0'),
    ).join('')
    await sendAccountEmail(platform, {
      to,
      subject: `${action} — Threadly`,
      text: `${action}: ${url}`,
      html: `<p><a href="${escaped}">${action}</a></p>`,
      idempotencyKey,
    })
  }
  return betterAuth({
    appName: 'Threadly',
    baseURL: env.authUrl,
    basePath: '/api/auth',
    secret,
    database: drizzleAdapter(createDb(platform.db), {
      provider: 'sqlite',
      schema,
      transaction: false,
    }),
    // Snapshot before the endpoint reads/verifies a credential. The DB trigger is
    // the final atomic check if reset races the session-create hook itself.
    hooks: {
      before: createAuthMiddleware(async (ctx) => {
        if (
          ctx.path === '/update-user' &&
          ctx.body?.aiProcessingNoticeVersion !== undefined
        )
          throw new APIError('BAD_REQUEST', {
            message: 'Processing notice receipts are recorded only at signup.',
          })
        if (
          ctx.path !== '/sign-in/email' ||
          typeof ctx.body?.email !== 'string'
        )
          return
        const owner = await platform.db
          .prepare(
            'SELECT id, credential_generation FROM "user" WHERE email = ?',
          )
          .bind(ctx.body.email.toLowerCase())
          .first<{ id: string; credential_generation: number }>()
        return {
          context: {
            context: {
              credentialFence: owner
                ? { userId: owner.id, generation: owner.credential_generation }
                : null,
            },
          },
        }
      }),
    },
    databaseHooks: {
      session: {
        create: {
          before: async (session, context) => {
            const fence = (
              context?.context as
                | { credentialFence?: { userId: string; generation: number } }
                | undefined
            )?.credentialFence
            if (
              context?.path !== '/sign-in/email' ||
              !fence ||
              fence.userId !== session.userId
            )
              return false
            const current = await platform.db
              .prepare('SELECT credential_generation FROM "user" WHERE id = ?')
              .bind(session.userId)
              .first<{ credential_generation: number }>()
            if (current?.credential_generation !== fence.generation)
              return false
            return {
              data: { ...session, credentialGeneration: fence.generation },
            }
          },
        },
      },
    },
    user: {
      deleteUser: { enabled: false },
      additionalFields: {
        aiProcessingNoticeVersion: {
          type: 'string',
          required: false,
          input: true,
          returned: false,
        },
        credentialGeneration: {
          type: 'number',
          defaultValue: 0,
          input: false,
          returned: false,
        },
      },
    },
    trustedOrigins: [new URL(env.authUrl).origin],
    emailAndPassword: {
      enabled: true,
      requireEmailVerification: true,
      minPasswordLength: 12,
      maxPasswordLength: 128,
      resetPasswordTokenExpiresIn: 3600,
      revokeSessionsOnPasswordReset: true,
      sendResetPassword: async ({ user, url }) =>
        sendLink(user.email, url, 'Reset your password'),
    },
    emailVerification: {
      sendOnSignUp: true,
      sendOnSignIn: true,
      autoSignInAfterVerification: false,
      expiresIn: 3600,
      sendVerificationEmail: async ({ user, url }) =>
        sendLink(user.email, url, 'Verify your email'),
    },
    session: {
      additionalFields: {
        credentialGeneration: {
          type: 'number',
          defaultValue: 0,
          input: false,
          returned: false,
        },
      },
      expiresIn: 60 * 60 * 24 * 7,
      updateAge: 60 * 60 * 24,
      cookieCache: { enabled: false },
    },
    rateLimit: {
      enabled: true,
      storage: 'database',
      modelName: 'rate_limit',
      window: 60,
      max: 100,
      customRules: {
        '/sign-in/email': { window: 60, max: 10 },
        '/sign-up/email': { window: 60, max: 5 },
        '/request-password-reset': { window: 60, max: 5 },
        '/send-verification-email': { window: 60, max: 5 },
      },
    },
    advanced: {
      useSecureCookies: !local,
      defaultCookieAttributes: { httpOnly: true, sameSite: 'lax', path: '/' },
      disableOriginCheck: false,
      ipAddress: { ipAddressHeaders: ['cf-connecting-ip'] },
      backgroundTasks: { handler: (work) => platform.waitUntil(work) },
    },
    // Auth errors must never dump request bodies, tokens or delivery links.
    logger: { disabled: true },
    telemetry: { enabled: false },
  })
}
